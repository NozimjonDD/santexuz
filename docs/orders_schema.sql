-- SQL-first domain design; Django migrations are the executable schema authority.
-- PostgreSQL. Foreign key targets: users_user, catalog_region, catalog_servicegroup.
CREATE TABLE orders_order (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint NOT NULL REFERENCES users_user(id), plumber_id bigint REFERENCES users_user(id),
 store_id bigint REFERENCES users_user(id), region_id bigint NOT NULL REFERENCES catalog_region(id),
 service_group_id bigint NOT NULL REFERENCES catalog_servicegroup(id),
 status varchar(32) NOT NULL, address text NOT NULL, latitude numeric(9,6) NOT NULL,
 longitude numeric(9,6) NOT NULL, consent_at timestamptz NOT NULL,
 quote_version integer NOT NULL DEFAULT 0, approved_version integer,
 preparation_started_at timestamptz, work_started_at timestamptz,
 created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
-- Each immutable quote snapshots tariff, labels, units, warranties, commissions and advance.
CREATE TABLE orders_quote (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES orders_order(id), version integer NOT NULL,
 snapshot jsonb NOT NULL, total numeric(16,2) NOT NULL CHECK(total >= 0),
 advance_required numeric(16,2) NOT NULL CHECK(advance_required >= 0),
 created_at timestamptz NOT NULL, UNIQUE(order_id,version)
);
CREATE TABLE orders_payment (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES orders_order(id), amount numeric(16,2) NOT NULL CHECK(amount > 0),
 kind varchar(16) NOT NULL, method varchar(16) NOT NULL,
 idempotency_key varchar(128) NOT NULL UNIQUE, received_by_id bigint NOT NULL REFERENCES users_user(id),
 created_at timestamptz NOT NULL
);
-- Remaining ORM-owned tables: ServiceItem, MaterialItem, Contract, Delivery,
-- DeliveryItem, Issue, Refund, CashHandover, Settlement, Rating, Attachment, OrderEvent.
-- Every mutation locks its Order first. DeliveryItem allocations cannot exceed the
-- approved material quantities. One delivery fee lives on Quote, never Delivery.
-- Refunds <= receipts; partner settlements <= snapshot net; disputes block residual
-- collection and settlement. Immutable journals are append-only in ORM and DB triggers.
