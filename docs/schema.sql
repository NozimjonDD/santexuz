-- SQL-first design, PostgreSQL. Django migrations are the schema authority.
-- This design describes domain tables before implementation; DO NOT apply it
-- in addition to migrations. Auth/permission and M2M tables use Django migrations.
-- UZS money uses NUMERIC(14,2), quantities NUMERIC(12,3), never binary floats.
-- All domain tables have BIGINT identities and created_at/updated_at timestamps.

CREATE TABLE catalog_region (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL, code VARCHAR(50) NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE catalog_servicegroup (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL, name_ru VARCHAR(150) NOT NULL DEFAULT '',
 name_en VARCHAR(150) NOT NULL DEFAULT '', code VARCHAR(50) NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE catalog_service (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id BIGINT NOT NULL REFERENCES catalog_servicegroup(id),
 name VARCHAR(200) NOT NULL, name_ru VARCHAR(200) NOT NULL DEFAULT '',
 name_en VARCHAR(200) NOT NULL DEFAULT '', unit VARCHAR(30) NOT NULL,
 warranty_days INTEGER NOT NULL CHECK(warranty_days >= 0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE catalog_servicerate (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 region_id BIGINT NOT NULL REFERENCES catalog_region(id),
 service_id BIGINT NOT NULL REFERENCES catalog_service(id),
 unit_price NUMERIC(14,2) NOT NULL CHECK(unit_price >= 0),
 urgent_fee NUMERIC(14,2) NOT NULL CHECK(urgent_fee >= 0),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(region_id,service_id)
);
CREATE TABLE catalog_material (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL, unit VARCHAR(30) NOT NULL,
 brand VARCHAR(150) NOT NULL DEFAULT '', is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE catalog_servicecenter (
 id BIGINT PRIMARY KEY CHECK(id=1), name VARCHAR(200) NOT NULL,
 address TEXT NOT NULL, phone VARCHAR(20) NOT NULL,
 opening_time TIME NOT NULL, closing_time TIME NOT NULL,
 working_days JSONB NOT NULL,
 default_plumber_commission NUMERIC(5,2) NOT NULL CHECK(default_plumber_commission BETWEEN 0 AND 100),
 default_store_commission NUMERIC(5,2) NOT NULL CHECK(default_store_commission BETWEEN 0 AND 100),
 advance_kind VARCHAR(10) NOT NULL CHECK(advance_kind IN ('percent','fixed')),
 advance_value NUMERIC(14,2) NOT NULL CHECK(advance_value >= 0),
 plumber_response_minutes INTEGER NOT NULL CHECK(plumber_response_minutes > 0),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CHECK(advance_kind <> 'percent' OR advance_value <= 100)
);
CREATE TABLE catalog_contracttemplate (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 language VARCHAR(2) NOT NULL CHECK(language IN ('uz','ru','en')),
 version INTEGER NOT NULL CHECK(version > 0), text TEXT NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(language,version)
);
-- users_user extends Django AbstractUser (username/password/is_staff/groups).
-- Domain additions: telegram_id BIGINT UNIQUE NULL CHECK(telegram_id > 0), role customer/plumber/store,
-- phone_number VARCHAR(20), phone_verified_at TIMESTAMPTZ NULL, language uz/ru/en.
CREATE TABLE users_plumberprofile (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES users_user(id),
 commission_rate NUMERIC(5,2) NULL CHECK(commission_rate BETWEEN 0 AND 100),
 experience_years SMALLINT NOT NULL CHECK(experience_years >= 0),
 photo VARCHAR(100) NOT NULL DEFAULT '', is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
-- users_plumberprofile_regions and users_plumberprofile_services are M2M
-- join tables with pair uniqueness and foreign keys to Region/ServiceGroup.
CREATE TABLE users_store (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES users_user(id),
 name VARCHAR(200) NOT NULL, address TEXT NOT NULL,
 latitude NUMERIC(9,6) NULL CHECK(latitude BETWEEN -90 AND 90),
 longitude NUMERIC(9,6) NULL CHECK(longitude BETWEEN -180 AND 180),
 commission_rate NUMERIC(5,2) NULL CHECK(commission_rate BETWEEN 0 AND 100),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE common_auditevent (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NULL REFERENCES users_user(id), action VARCHAR(100) NOT NULL,
 object_type VARCHAR(100) NOT NULL, object_id VARCHAR(100) NOT NULL,
 payload JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
-- UPDATE and DELETE on common_auditevent are rejected by DB triggers.
-- Actor deletion is protected, preserving traceability. DB owners can alter
-- triggers; production DB administration requires separate trusted credentials.
-- Contract template language/version/text are immutable; active state may change.
